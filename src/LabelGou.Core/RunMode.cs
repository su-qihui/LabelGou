namespace LabelGou.Core;

/// <summary>
/// 软件的运行模式（阶段 29 定的框架，第 30 棒落地）。
/// <para>用户 2026-09-10 的原话是「**AI 模式导入表格后不应该直接绑定数据，先把表格给 AI 理解后由 AI 绑定**」——
/// 程序按表头猜出来的绑定，正是他要换掉的东西。所以「导入后先不绑定、交 AI 读」是**主推路径**。</para>
/// <para>而离线模式必须是**随时能切回去的退路**：没配密钥、断网、模型超时，都不该把人堵在"等 AI"上。
/// 他没明说但必然成立的还有一条：**离线模式的行为一个字都不许变**（自动连线 + 人工连线照旧）。</para>
/// <para>默认给 <see cref="Ai"/>（用户 2026-09-10 明确选的，不是"首次问一次"）。</para>
/// </summary>
public enum RunMode
{
    /// <summary>AI 模式（默认）：导入后不先绑定，交 AI 读整张表并给出绑定方案，人逐条确认才落地。</summary>
    Ai = 0,

    /// <summary>离线模式：现有的自动连线 + 人工连线，全程不碰网络。</summary>
    Offline = 1,
}
